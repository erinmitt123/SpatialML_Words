using System;
using ByteDance.PICO.SecureMR;
using ByteDance.PICO.XR;
using UnityEngine;

namespace PicoXR.SpatialML.Demo
{
    [DisallowMultipleComponent]
    public sealed class FaceDetectionPipelineZooDemo : MonoBehaviour, ISpatialMLServiceCleanup
    {
        private const string DetectionPipelineId = "detection";
        private const string DisplayPipelineId = "display";

        [Header("Pipeline Zoo Package")]
        [Tooltip("The SpatialMLPipelineZooAsset generated by the Pipeline Zoo importer.")]
        public SpatialMLPipelineZooAsset facePipelinePackage;

        [Header("Runtime")]
        [Min(1)] public int vstWidth = 580;
        [Min(1)] public int vstHeight = 326;
        [Min(0f)] public float submitIntervalSeconds = 0.05f;

        private Provider m_provider;
        private SpatialMLPipelineZooBundle m_bundle;
        private SpatialMLPipelineZooPipeline m_detectionPipeline;
        private SpatialMLPipelineZooPipeline m_displayPipeline;
        private float m_nextSubmitTime;
        private bool m_isShuttingDown;

        private void Awake()
        {
            PXR_Manager.EnableVideoSeeThrough = true;
            Application.targetFrameRate = 30;
        }

        private void Start()
        {
            if (facePipelinePackage == null)
            {
                Debug.LogError(
                    "FaceDetectionPipelineZooDemo requires an imported SpatialMLPipelineZooAsset. " +
                    "Import the face package, then assign the generated asset.");
                enabled = false;
                return;
            }

            try
            {
                m_provider = new Provider(vstWidth, vstHeight);
                m_bundle = SpatialMLPipelineZoo.LoadPackage(
                    m_provider,
                    facePipelinePackage,
                    DetectionPipelineId,
                    DisplayPipelineId);
                m_detectionPipeline = m_bundle[DetectionPipelineId];
                m_displayPipeline = m_bundle[DisplayPipelineId];

                Debug.Log(
                    $"Loaded Pipeline Zoo package '{facePipelinePackage.packageId}' with " +
                    $"'{DetectionPipelineId}' and '{DisplayPipelineId}' pipelines.");
            }
            catch (Exception exception)
            {
                Debug.LogException(exception, this);
                ShutdownSpatialML();
                enabled = false;
            }
        }

        private void Update()
        {
            if (m_isShuttingDown ||
                m_provider == null ||
                m_detectionPipeline == null ||
                m_displayPipeline == null ||
                Time.unscaledTime < m_nextSubmitTime)
            {
                return;
            }

            m_nextSubmitTime = Time.unscaledTime + submitIntervalSeconds;
            ulong detectionRun = m_detectionPipeline.Execute();
            m_displayPipeline.ExecuteAfter(detectionRun);
        }

        private void OnDestroy()
        {
            ShutdownSpatialML();
        }

        private void OnApplicationQuit()
        {
            ShutdownSpatialML();
        }

        public void ShutdownSpatialML()
        {
            if (m_isShuttingDown || m_provider == null)
            {
                return;
            }

            m_isShuttingDown = true;
            enabled = false;

            Provider providerToDestroy = m_provider;
            m_provider = null;
            m_bundle = null;
            m_detectionPipeline = null;
            m_displayPipeline = null;
            providerToDestroy.Destroy();
        }
    }
}
